#!/usr/bin/env python3
"""Generate the dark-mode block of every story stylesheet from its light colours.

The stories are drawn with a light palette (docs/stories/<id>/story.css and the shared story.css). The site
has a light/dark toggle (Material's `body[data-md-color-scheme="slate"]`), and a story should follow it. Rather
than keep ten palettes by hand in two schemes, the dark one is derived from the light one: every colour in a
rule is mapped to the same hue with its lightness mirrored (white becomes near-black, near-black becomes
near-white) and slightly less saturated, and the result is written as `body[data-md-color-scheme="slate"] ...`
rules at the end of the same file, between two marker comments.

Rules with a dark background of their own (the terminal-style output boxes) are left alone, so a dark panel
stays dark in both schemes. Inline SVG art in the story scripts is not touched (a white chef's hat is fine on a
dark stage). `box-shadow` and `text-shadow` are not mapped, and `@keyframes` are skipped.

Usage:
  python3 scripts/story_dark.py            rewrite the generated block in every docs/stories/*/story.css
  python3 scripts/story_dark.py --check    exit 1 if any block is out of date (CI runs this)

Edit the light colours, then run it. Do not edit between the markers by hand. A hand-tuned exception belongs
in the OVERRIDES table below.
"""

from __future__ import annotations

import colorsys
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORIES = ROOT / "docs" / "stories"
BEGIN = "/* ==== dark mode: generated by scripts/story_dark.py from the colours above; do not edit by hand ==== */"
END = "/* ==== end of generated dark mode ==== */"
SCHEME = 'body[data-md-color-scheme="slate"]'

# Lightness mirror: white -> LOW, black -> HIGH. Saturation is eased so pastels do not glow on a dark stage.
LOW, HIGH = 0.085, 0.93
SAT = 0.82
MID_FLOOR = 0.68
DARK_PANEL = 0.25  # a rule whose own background is darker than this is a dark panel and is left alone

# Hand-tuned exceptions: (file stem, exact light colour) -> dark colour. Empty until a story needs one.
OVERRIDES: dict[tuple[str, str], str] = {}

HEX = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
FUNC = re.compile(r"rgba?\(\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*(?:,\s*([0-9.]+)\s*)?\)")
COLOR = re.compile(f"{HEX.pattern}|{FUNC.pattern}")
SKIP_PROPS = {"box-shadow", "text-shadow", "filter", "backdrop-filter", "-webkit-tap-highlight-color"}


def parse_color(text: str) -> tuple[float, float, float, float | None] | None:
    if text.startswith("#"):
        h = text[1:]
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else None
        return r, g, b, a
    m = FUNC.fullmatch(text)
    if not m:
        return None
    r, g, b = (float(m.group(i)) / 255 for i in (1, 2, 3))
    return r, g, b, (float(m.group(4)) if m.group(4) is not None else None)


def lightness(text: str) -> float | None:
    c = parse_color(text)
    if not c:
        return None
    return colorsys.rgb_to_hls(c[0], c[1], c[2])[1]


def mirror(text: str, stem: str) -> str:
    if (stem, text.lower()) in OVERRIDES:
        return OVERRIDES[(stem, text.lower())]
    c = parse_color(text)
    if not c:
        return text
    r, g, b, a = c
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l2 = LOW + (1 - l) * (HIGH - LOW)
    # A fill dark enough to carry white text (buttons, badges) becomes a fill light enough to carry the dark text
    # that white turns into, with a little margin for AA contrast.
    if 0.2 <= l <= 0.55:
        l2 = max(l2, MID_FLOOR)
    r2, g2, b2 = colorsys.hls_to_rgb(h, l2, s * SAT)
    rgb = tuple(round(v * 255) for v in (r2, g2, b2))
    if a is not None and text.startswith("rgb"):
        return f"rgba({rgb[0]}, {rgb[1]}, {rgb[2]}, {a:g})"
    out = "#%02x%02x%02x" % rgb
    return out + ("%02x" % round(a * 255)) if a is not None else out


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def split_decls(body: str) -> list[tuple[str, str]]:
    out, depth, cur = [], 0, ""
    for ch in body:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == ";" and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    decls = []
    for d in out:
        if ":" in d:
            prop, _, value = d.partition(":")
            decls.append((prop.strip(), value.strip()))
    return decls


def blocks(css: str):
    """Yield (prelude, body) for each top-level block; the body of an at-rule is itself CSS."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield prelude, css[j + 1 : k - 1]
        i = k


def dark_rule(selectors: str, body: str, stem: str) -> str | None:
    decls = split_decls(body)
    # A rule with its own dark background is a dark panel: keep it as it is in both schemes.
    for prop, value in decls:
        if prop in ("background", "background-color") and "gradient" not in value:
            m = COLOR.search(value)
            if m and (lightness(m.group(0)) or 1) < DARK_PANEL:
                return None
    kept = []
    for prop, value in decls:
        if prop in SKIP_PROPS or "url(" in value or not COLOR.search(value):
            continue
        kept.append(f"  {prop}: {COLOR.sub(lambda m: mirror(m.group(0), stem), value)};")
    if not kept:
        return None
    sels = ",\n".join(f"{SCHEME} {s.strip()}" for s in selectors.split(",") if s.strip())
    return f"{sels} {{\n" + "\n".join(kept) + "\n}"


def generate(css: str, stem: str) -> str:
    out: list[str] = []
    for prelude, body in blocks(strip_comments(css)):
        if prelude.startswith("@keyframes") or prelude.startswith("@font-face"):
            continue
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            inner = [r for p, b in blocks(body) if (r := dark_rule(p, b, stem))]
            if inner:
                out.append(f"{prelude} {{\n" + "\n".join(inner) + "\n}")
            continue
        if prelude.startswith("@"):
            continue
        rule = dark_rule(prelude, body, stem)
        if rule:
            out.append(rule)
    return "\n\n".join(out)


def split_generated(text: str) -> str:
    """The stylesheet without its generated block."""
    if BEGIN in text:
        text = text[: text.index(BEGIN)]
    return text.rstrip() + "\n"


def render(path: Path) -> str:
    base = split_generated(path.read_text(encoding="utf-8"))
    return f"{base}\n{BEGIN}\n{generate(base, path.parent.name)}\n{END}\n"


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path in sorted(STORIES.glob("*/story.css")):
        new = render(path)
        if new != path.read_text(encoding="utf-8"):
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(new, encoding="utf-8")
    if check and stale:
        print("the dark-mode block is out of date in: " + ", ".join(str(p) for p in stale))
        print("run: python3 scripts/story_dark.py")
        return 1
    print(("up to date: " if check else "wrote ") + f"{len(list(STORIES.glob('*/story.css')))} stylesheets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
